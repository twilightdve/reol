// ヘルパー関数: IDで会場を検索
export function getVenueById(id: string): Venue | undefined {
  return VENUES_2026.find(venue => venue.id === id)
}

// ヘルパー関数: IDと言語で会場を検索
export function getVenueByIdAndLocale(id: string, locale: 'ja' | 'en'): Venue | undefined {
  if (locale === 'en') {
    return VENUES_2026_EN.find(venue => venue.id === id)
  }
  return VENUES_2026.find(venue => venue.id === id)
}

// ヘルパー関数: 全会場を日付順（ソート済み）で取得
export function getAllVenuesSorted(): Venue[] {
  return VENUES_2026
}

// ヘルパー関数: 全会場を言語別に日付順で取得
export function getAllVenuesSortedByLocale(locale: 'ja' | 'en'): Venue[] {
  return locale === 'en' ? VENUES_2026_EN : VENUES_2026
}

